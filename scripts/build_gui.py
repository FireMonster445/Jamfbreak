#!/usr/bin/env python3
"""
Build the Jamfbreak React frontend and bundle it for pywebview.

Steps:
  1. npm install (skipped when node_modules already exists)
  2. npm run build -> frontend/dist/index.html (single self-contained file)
  3. regenerate jamfbreak/gui_bundle.py, a compressed Python module

The GUI ships the compiled bundle inside the package (and therefore
inside the PyInstaller EXE unchanged): at startup jamfbreak.gui decodes
it to a Jamfbreak.html file beside the running code and opens it as a
file:// URL (pywebview's html= / NavigateToString path is avoided — see
jamfbreak/gui.py). Re-run this script after editing frontend/:

    python scripts/build_gui.py
"""

from __future__ import annotations

import base64
import importlib
import subprocess
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "frontend"
DIST_INDEX = FRONTEND / "dist" / "index.html"
BUNDLE = ROOT / "jamfbreak" / "gui_bundle.py"


def run(cmd: list[str], cwd: Path) -> None:
    print(f"+ {' '.join(cmd)} (cwd={cwd.relative_to(ROOT)})")
    subprocess.run(cmd, cwd=cwd, check=True)


def npm_cmd(*names: str) -> list[str]:
    npm = "npm.cmd" if sys.platform == "win32" else "npm"
    return [npm, *names]


def main() -> int:
    if not (FRONTEND / "package.json").is_file():
        print("frontend/package.json missing", file=sys.stderr)
        return 1

    if not (FRONTEND / "node_modules").is_dir():
        run(npm_cmd("install"), FRONTEND)
    run(npm_cmd("run", "build"), FRONTEND)

    if not DIST_INDEX.is_file():
        print(f"vite build did not produce {DIST_INDEX}", file=sys.stderr)
        return 1

    html = DIST_INDEX.read_text(encoding="utf-8")

    compressed = base64.b64encode(zlib.compress(html.encode("utf-8"), 9)).decode(
        "ascii"
    )
    lines = [
        '    "%s"' % compressed[i : i + 96] for i in range(0, len(compressed), 96)
    ]

    payload = (
        '"""\n'
        "Compiled React frontend for the Jamfbreak GUI.\n\n"
        "Generated by scripts/build_gui.py - edit frontend/src instead and rebuild.\n"
        '"""\n\n'
        "import base64\n"
        "import zlib\n\n"
        "_HTML_GZIP_B64 = (\n"
        + "\n".join(lines)
        + "\n)\n\n"
        "HTML = zlib.decompress(base64.b64decode(_HTML_GZIP_B64)).decode(\n"
        '    "utf-8"\n'
        ")\n"
    )
    BUNDLE.write_text(payload, encoding="utf-8", newline="\n")
    print(f"wrote {BUNDLE.name} (b64={len(compressed)} bytes, html={len(html)} chars)")

    # Import + contract sanity check on the freshly written module.
    importlib.invalidate_caches()
    sys.path.insert(0, str(ROOT))
    import jamfbreak.gui_bundle as bundle  # noqa: E402

    assert "<title>Jamfbreak</title>" in bundle.HTML
    assert "pywebview" in bundle.HTML
    print("bundle import + contract checks OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
